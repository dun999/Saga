using json = nlohmann::json;

std::string cookie(const httplib::Request& req, const std::string& name) {
  const std::string all = req.get_header_value("Cookie");
  const std::string key = name + "=";
  for (size_t p = 0; p < all.size();) {
    while (p < all.size() && (all[p] == ' ' || all[p] == ';')) ++p;
    const size_t e = all.find(';', p);
    const std::string kv = all.substr(p, e == std::string::npos ? std::string::npos : e - p);
    if (kv.starts_with(key)) return kv.substr(key.size());
    if (e == std::string::npos) break;
    p = e + 1;
  }
  return "";
}

// Namespaces embed the uid, so keep it to a safe, bounded alphabet.
std::string sanitize_uid(const std::string& s) {
  std::string out;
  for (char c : s) {
    const unsigned char u = static_cast<unsigned char>(c);
    if (std::isalnum(u) || c == '-' || c == '_') out += static_cast<char>(std::tolower(u));
    if (out.size() >= 80) break;  // room for a full 0x Sui address
  }
  return out;
}

// Wallet memory lives under the 0x address. A username that looks like one would open someone else's
// wallet memory without their signature, so usernames can't take that shape.
bool looks_like_address(const std::string& uid) {
  return uid.size() > 2 && uid.starts_with("0x") &&
         std::all_of(uid.begin() + 2, uid.end(), [](unsigned char c) { return std::isxdigit(c); });
}

void send_json(httplib::Response& res, const json& j, int status = 200) {
  res.status = status;
  res.set_content(j.dump(), "application/json");
}

// Broadcasts memory-write events to connected SSE clients.
struct Hub {
  std::mutex mu;
  std::condition_variable cv;
  std::deque<std::pair<uint64_t, memwal::WriteRecord>> events;
  uint64_t seq = 0;
  void push(const memwal::WriteRecord& r) {
    std::lock_guard lk(mu);
    events.emplace_back(++seq, r);
    while (events.size() > 500) events.pop_front();
    cv.notify_all();
  }
};

// A write is shown to the user it belongs to: their own namespaces, or shared-namespace writes their
// turns produced (blackboard, lessons, skills, improvements). Only content-free harness writes
// (prompt versions, scores) are public.
bool visible_to(const memwal::WriteRecord& r, const std::string& uid) {
  if (r.ns.starts_with("u:")) return r.ns.starts_with("u:" + uid + ":");
  return r.owner.empty() ? !r.ns.starts_with("task:") : r.owner == uid;
}

